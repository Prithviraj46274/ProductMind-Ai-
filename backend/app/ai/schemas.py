"""
ProductMind AI — AI Schemas & Payloads
Defines request and response schemas for AI chat inputs, health diagnostics,
and structured generation targets.
"""

from typing import Any, Dict, Literal, Optional
from pydantic import BaseModel, Field


class ChatMessageInput(BaseModel):
    """Represents a single chat turn input for multi-turn or contextual prompts."""
    role: Literal["system", "user", "assistant"] = Field(
        ...,
        description="Role of the message sender.",
        examples=["user"],
    )
    content: str = Field(
        ...,
        min_length=1,
        description="Text content of the message.",
        examples=["Hello Gemini!"],
    )


class AIHealthResponse(BaseModel):
    """Sanitized diagnostic report of AI service readiness and active configuration."""
    status: str = Field(
        ...,
        description="Status indicator ('ready', 'unconfigured', 'degraded').",
        examples=["ready"],
    )
    provider: str = Field(
        ...,
        description="Configured LLM provider.",
        examples=["google"],
    )
    model: str = Field(
        ...,
        description="Configured active model identifier.",
        examples=["gemini-3.8-flash"],
    )
    is_configured: bool = Field(
        ...,
        description="Whether required credentials for the active provider are present.",
        examples=[True],
    )
    temperature: float = Field(..., description="Default model temperature.")
    max_output_tokens: int = Field(..., description="Default max output token limit.")
    timeout_seconds: int = Field(..., description="Default request timeout in seconds.")
    max_retries: int = Field(..., description="Default maximum retry attempts.")


class AITestRequest(BaseModel):
    """Payload for manual or automated connectivity diagnostics."""
    prompt: Optional[str] = Field(
        default="Hello ProductMind AI! Confirm LLM foundation is operational.",
        description="Diagnostic test prompt to send to the LLM.",
        max_length=500,
    )
    system_instruction: Optional[str] = Field(
        default="You are ProductMind AI Copilot assistant. Reply concisely in 15 words or less.",
        description="Optional system instruction for the test invocation.",
        max_length=500,
    )


class AITestResponse(BaseModel):
    """Response payload for connectivity test execution."""
    status: Literal["success", "error"] = Field(..., description="Execution status.")
    provider: str = Field(..., description="Provider used for generation.")
    model: str = Field(..., description="Model ID used for generation.")
    prompt: str = Field(..., description="The prompt sent to the model.")
    response: str = Field(..., description="The text response generated by the model.")
    latency_ms: Optional[float] = Field(None, description="Execution latency in milliseconds.")

