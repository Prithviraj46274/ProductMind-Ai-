"""
ProductMind AI — Feature Intelligence Agent Schemas
Defines Pydantic v2 input, output, analysis, and API contracts for semantic feature grouping,
duplicate detection, demand aggregation, and consolidated feature intelligence generation.
"""

from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class AnalysisStatus(str, Enum):
    COMPLETED = "completed"
    AMBIGUOUS = "ambiguous"
    INSUFFICIENT_INFORMATION = "insufficient_information"


class DuplicateType(str, Enum):
    EXACT_DUPLICATE = "exact_duplicate"
    NEAR_DUPLICATE = "near_duplicate"
    SEMANTIC_EQUIVALENT = "semantic_equivalent"
    RELATED_DISTINCT = "related_distinct"
    UNRELATED = "unrelated"


class FeatureRequestCandidate(BaseModel):
    """Normalized representation of an eligible customer feature request candidate."""
    feedback_id: str = Field(..., description="Unique feedback item identifier")
    title: str = Field(..., description="Feedback title or summary line")
    description: str = Field(default="", description="Detailed feedback body text")
    category: str = Field(default="Feature Request", description="Primary classification category")
    main_theme: Optional[str] = Field(default=None, description="Main theme extracted by Feedback Intelligence")
    customer_pain_point: Optional[str] = Field(default=None, description="Core customer pain point or friction")
    sentiment: Optional[str] = Field(default=None, description="Evaluated sentiment (Positive, Neutral, Negative, Mixed)")
    urgency: Optional[str] = Field(default=None, description="Evaluated urgency (Critical, High, Medium, Low)")
    customer_id: Optional[str] = Field(default=None, description="Unique customer identifier or email for demand deduplication")
    customer_name: Optional[str] = Field(default=None, description="Customer or user display name")
    company_name: Optional[str] = Field(default=None, description="Customer company or account name")


class FeatureGroupAnalysis(BaseModel):
    """
    Structured output generated by the LLM for a proposed consolidated feature group.
    Grounds all summaries, themes, and pain points in original feedback text.
    """
    group_name: str = Field(
        ...,
        min_length=3,
        max_length=200,
        description="Concise, product-oriented feature title (e.g. 'Dark Mode Support')",
    )
    feature_summary: str = Field(
        ...,
        min_length=10,
        description="High-level 1-2 sentence executive summary of the requested capability",
    )
    consolidated_description: str = Field(
        ...,
        min_length=10,
        description="Comprehensive product synthesis grounded in customer feedback statements",
    )
    related_feedback_ids: List[str] = Field(
        ...,
        min_length=1,
        description="Verbatim list of feedback IDs that belong to this feature group",
    )
    common_themes: List[str] = Field(
        default_factory=list,
        description="Shared product themes across grouped requests",
    )
    common_pain_points: List[str] = Field(
        default_factory=list,
        description="Shared customer frictions, blockers, or desired outcomes",
    )
    evidence: List[str] = Field(
        default_factory=list,
        description="Verbatim excerpts from original feedback supporting this grouping",
    )
    suggested_capability: Optional[str] = Field(
        default=None,
        description="Suggested specific feature capability, setting, or enhancement",
    )
    grouping_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Calibrated confidence score between 0.0 and 1.0",
    )
    grouping_reason: str = Field(
        ...,
        min_length=5,
        description="Evidence-based justification explaining why these requests represent the same capability",
    )
    analysis_status: AnalysisStatus = Field(
        default=AnalysisStatus.COMPLETED,
        description="Analysis state (completed, ambiguous, insufficient_information)",
    )

    @field_validator("related_feedback_ids")
    @classmethod
    def validate_unique_feedback_ids(cls, v: List[str]) -> List[str]:
        if not v:
            raise ValueError("related_feedback_ids cannot be empty")
        seen = set()
        deduped = []
        for fid in v:
            fid_clean = str(fid).strip()
            if fid_clean and fid_clean not in seen:
                seen.add(fid_clean)
                deduped.append(fid_clean)
        if not deduped:
            raise ValueError("related_feedback_ids must contain at least one valid ID")
        return deduped


class FeatureGroupingAgentOutput(BaseModel):
    """Root structured output produced by FeatureIntelligenceAgent invocation."""
    groups: List[FeatureGroupAnalysis] = Field(
        default_factory=list,
        description="Consolidated feature groups identified from feedback",
    )
    feature_groups: Optional[List[FeatureGroupAnalysis]] = Field(
        default=None,
        description="Alias for groups",
    )
    ungrouped_feedback_ids: List[str] = Field(
        default_factory=list,
        description="Feedback IDs that do not belong to any cluster or represent distinct single requests",
    )
    overall_reasoning: str = Field(
        default="",
        description="Synthesis of capability boundaries, cluster separations, and distinction rationales",
    )

    @model_validator(mode="before")
    @classmethod
    def normalize_groups(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Unpack single outer wrapper if reasoning model wrapped payload (e.g. {'###': {...}}, {'output': {...}})
            if len(data) == 1:
                first_k = next(iter(data))
                if isinstance(data[first_k], dict) and any(
                    k in data[first_k]
                    for k in ("groups", "feature_groups", "Feature_Groups", "FeatureGroups", "clusters")
                ):
                    data = data[first_k]

            if "feature_groups" in data and ("groups" not in data or not data["groups"]):
                data["groups"] = data["feature_groups"]
            elif "Feature_Groups" in data and ("groups" not in data or not data["groups"]):
                data["groups"] = data["Feature_Groups"]
            elif "FeatureGroups" in data and ("groups" not in data or not data["groups"]):
                data["groups"] = data["FeatureGroups"]
            elif "clusters" in data and ("groups" not in data or not data["groups"]):
                data["groups"] = data["clusters"]
        return data

    @model_validator(mode="after")
    def sync_groups(self) -> "FeatureGroupingAgentOutput":
        if self.feature_groups is None and self.groups:
            self.feature_groups = self.groups
        elif not self.groups and self.feature_groups:
            self.groups = self.feature_groups
        return self


class DuplicateDetectionItem(BaseModel):
    """Analysis result comparing feedback items for duplication vs distinctness."""
    feedback_id: str = Field(..., description="Target feedback item ID")
    matched_feedback_id: Optional[str] = Field(default=None, description="Matching feedback item ID")
    matched_group_id: Optional[str] = Field(default=None, description="Existing feature group ID if matched")
    duplicate_type: DuplicateType = Field(..., description="Relationship classification")
    similarity_explanation: str = Field(
        ...,
        min_length=5,
        description="Detailed explanation explaining why requests are duplicates or distinct capabilities",
    )
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0")
    recommendation: str = Field(
        ...,
        min_length=5,
        description="Tactical product recommendation (e.g. 'Merge with Dark Mode', 'Keep as separate feature')",
    )


class DuplicateDetectionAgentOutput(BaseModel):
    """Structured output from LLM duplicate detection analysis."""
    duplicates: List[DuplicateDetectionItem] = Field(
        default_factory=list,
        description="Evaluated duplicate candidates",
    )
    summary: str = Field(default="", description="Executive summary of duplicate analysis")


class FeatureGroupResult(BaseModel):
    """
    Complete consolidated feature intelligence result model.
    Combines LLM semantic synthesis with deterministic Python-calculated demand metrics.
    """
    feature_group_id: str = Field(..., description="Unique feature group database identifier")
    workspace_id: str = Field(..., description="Associated workspace identifier")
    group_name: str = Field(..., description="Consolidated feature title")
    feature_summary: str = Field(..., description="Executive summary of requested capability")
    consolidated_description: str = Field(..., description="Grounded product description")
    related_feedback_ids: List[str] = Field(default_factory=list, description="Original feedback references")
    total_request_count: int = Field(default=0, ge=0, description="Exact count of related feedback requests")
    unique_customer_count: int = Field(default=0, ge=0, description="Exact count of unique requesting customers")
    sentiment_distribution: Dict[str, int] = Field(
        default_factory=dict,
        description="Tally of customer sentiment across member requests",
    )
    urgency_distribution: Dict[str, int] = Field(
        default_factory=dict,
        description="Tally of operational urgency across member requests",
    )
    common_themes: List[str] = Field(default_factory=list, description="Common thematic tags")
    common_pain_points: List[str] = Field(default_factory=list, description="Identified customer pain points")
    evidence: List[str] = Field(default_factory=list, description="Direct customer quotes")
    suggested_capability: Optional[str] = Field(default=None, description="Suggested product capability")
    grouping_confidence: float = Field(default=0.0, ge=0.0, le=1.0, description="Grouping confidence")
    grouping_reason: Optional[str] = Field(default=None, description="Rationale for grouping")
    grouping_status: str = Field(default="suggested", description="Feature group workflow status")
    created_at: Optional[datetime] = Field(default=None, description="Creation timestamp")
    updated_at: Optional[datetime] = Field(default=None, description="Last update timestamp")


