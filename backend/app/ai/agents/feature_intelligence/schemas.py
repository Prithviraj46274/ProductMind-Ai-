class GroupFeaturesRequest(BaseModel):
    """API request payload for grouping feedback into feature intelligence."""
    workspace_id: str = Field(..., min_length=1, description="Target workspace identifier")
    feedback_ids: Optional[List[str]] = Field(
        default=None,
        description="Explicit feedback IDs to analyze. If omitted or empty, evaluates unassigned feature requests in workspace.",
    )
    force_regroup: bool = Field(
        default=False,
        description="If True, re-analyzes and regroups feedback items even if already assigned to a feature group.",
    )
    confidence_threshold: float = Field(
        default=0.6,
        ge=0.0,
        le=1.0,
        description="Minimum confidence threshold required to accept a feature group.",
    )
    min_group_size: int = Field(
        default=1,
        ge=1,
        description="Minimum number of feedback items required to form a group.",
    )


class GroupFeaturesResponse(BaseModel):
    """API response contract returning generated feature groups and execution metadata."""
    workspace_id: str = Field(..., description="Workspace ID")
    groups_created: int = Field(..., ge=0, description="Number of feature groups successfully generated and persisted")
    total_feedback_analyzed: int = Field(..., ge=0, description="Total eligible feature requests evaluated")
    groups: List[FeatureGroupResult] = Field(default_factory=list, description="Generated feature groups")
    ungrouped_feedback_ids: List[str] = Field(
        default_factory=list,
        description="Feedback items that remain standalone without a group match",
    )
    execution_metadata: Dict[str, Any] = Field(default_factory=dict, description="Execution telemetry and runtime stats")


class DuplicateDetectionRequest(BaseModel):
    """API request payload for detecting duplicate feedback items."""
    workspace_id: str = Field(..., min_length=1, description="Target workspace identifier")
    feedback_ids: Optional[List[str]] = Field(
        default=None,
        description="List of feedback IDs to evaluate for duplicate relationships",
    )
    target_feedback_id: Optional[str] = Field(
        default=None,
        description="Optional single feedback ID to compare against other items in the workspace",
    )


class DuplicateDetectionResponse(BaseModel):
    """API response contract returning duplicate detection results."""
    workspace_id: str = Field(..., description="Workspace ID")
    total_evaluated: int = Field(..., ge=0, description="Number of feedback records evaluated")
    duplicates_found: int = Field(..., ge=0, description="Number of duplicate relationships identified")
    results: List[DuplicateDetectionItem] = Field(default_factory=list, description="Itemized duplicate evaluation details")
    execution_metadata: Dict[str, Any] = Field(default_factory=dict, description="Execution telemetry")

